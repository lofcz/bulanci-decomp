/** Vite plugin that serves the catalog + unpacked overlay straight
 *  from the local filesystem under `/data/catalog/*` and
 *  `/data/overlay/*`.  Lets `bun run dev` work without a Python
 *  backend — the same layout the production static build expects. */
function bulanciDataSource(): Plugin {
  return {
    name: "bulanci-data-source",
    configureServer(server) {
      server.middlewares.use(async (req, res, next) => {
        const url    = req.url ?? "";
        const method = req.method ?? "GET";
        try {
          // Capability probe — the React app pings this once at boot to
          // decide whether to expose editor controls.  Only the Vite
          // dev plugin replies 200; the static `serve.py` shim 404s.
          if (url === "/data/api/writable") {
            res.statusCode = 200;
            res.setHeader("Content-Type", "application/json");
            res.end(`{"writable":true}`);
            return;
          }

          if (url.startsWith("/data/catalog/overlay-index.json")) {
            return await sendOverlayIndex(res);
          }

          // Codegen handle table — sourced from open_bulanci/assets,
          // not catalogDir, so it gets its own route.  Optional: 404
          // when the assets haven't been built yet.
          if (url.startsWith("/data/catalog/manifest.json")) {
            try {
              const txt = await fsp.readFile(assetsManifest, "utf-8");
              res.statusCode = 200;
              res.setHeader("Content-Type",  "application/json");
              res.setHeader("Cache-Control", "no-store");
              res.end(txt);
            } catch {
              res.statusCode = 404;
              res.end("manifest.json not found");
            }
            return;
          }

          // Asset-editor write back: only `registry.json` for now,
          // since folder / slug / notes edits go through there.  Other
          // catalog files are regenerated by python scripts.
          if (
            method === "PUT" &&
            url === "/data/catalog/registry.json"
          ) {
            return await receiveRegistry(req, res);
          }

          // Scene discovery — flat list of every scene declared across the
          // load-order profile's paks (the scene editor's browser).
          if (url.split("?")[0] === "/data/scenes") {
            return await sendScenes(res);
          }

          // Pak script index — every `.luau` in a pak (the Scripts panel's
          // file browser, so it can open lib/startgame1.luau, poem.luau, …).
          if (url.split("?")[0].startsWith("/data/pak-scripts/")) {
            const pak = decodeURIComponent(url.slice("/data/pak-scripts/".length).split("?")[0]);
            return sendPakScripts(res, pak);
          }

          // Pak file IO for the scene editor — read/write a scene doc or
          // attached script by `<pakId>/<relpath>`. GET reads text, PUT
          // persists it (the native client's disk watcher then hot-reloads;
          // the same path in a higher mod pak overlays the base scene).
          if (url.startsWith("/data/pak/")) {
            const rel = decodeURIComponent(url.slice("/data/pak/".length).split("?")[0]);
            if (method === "PUT") return await writePakFile(req, res, rel);
            return await readPakFile(res, rel);
          }

          if (url.startsWith("/data/catalog/")) {
            const rel = decodeURIComponent(url.slice("/data/catalog/".length).split("?")[0]);
            return await sendFile(res, path.join(catalogDir, rel));
          }
          if (url.startsWith("/data/overlay/")) {
            const rel = decodeURIComponent(url.slice("/data/overlay/".length).split("?")[0]);
            return await sendFile(res, path.join(overlayDir, rel));
          }
        } catch (err) {
          console.error("[bulanci-data-source]", url, err);
          res.statusCode = 500;
          res.end("data source error");
          return;
        }
        next();
      });
    },
  };
}

/** Buffer the PUT body, validate it as JSON, and write it to
 *  `registry.json` atomically (write to `*.tmp` then rename, so a
 *  crash mid-write doesn't leave a half-rewritten registry behind). */
async function receiveRegistry(
  req:  import("node:http").IncomingMessage,
  res:  import("node:http").ServerResponse,
): Promise<void> {
  const chunks: Buffer[] = [];
  let   total = 0;
  // Refuse anything over a generous 4 MB so a runaway editor can't
  // exhaust memory.  registry.json is currently ~10 kB.
  const MAX_BYTES = 4 * 1024 * 1024;
  for await (const chunk of req) {
    chunks.push(chunk as Buffer);
    total += (chunk as Buffer).length;
    if (total > MAX_BYTES) {
      res.statusCode = 413;
      res.end("registry.json too large");
      return;
    }
  }
  const body = Buffer.concat(chunks).toString("utf-8");
  // Structural sanity check — confirm the payload parses as JSON
  // *and* has the registry's top-level shape before we overwrite the
  // file.  Catches the editor writing TOML / garbage by mistake.
  try {
    const obj = JSON.parse(body);
    if (typeof obj !== "object" || obj === null
        || !("assets" in obj || "scripts" in obj || "folders" in obj)) {
      throw new Error("missing top-level assets/scripts/folders");
    }
  } catch (err) {
    res.statusCode = 400;
    res.end(`payload is not a valid registry.json: ${err}`);
    return;
  }
  const target = path.join(catalogDir, "registry.json");
  const tmp    = `${target}.${process.pid}.tmp`;
  await fsp.writeFile(tmp, body, "utf-8");
  await fsp.rename(tmp, target);
  res.statusCode = 200;
  res.setHeader("Content-Type", "application/json");
  res.end(`{"ok":true,"bytes":${body.length}}`);
  console.log(`[bulanci-data-source] registry.json updated (${body.length} bytes)`);
}

async function sendFile(res: import("node:http").ServerResponse, filePath: string): Promise<void> {
  // Guard against `..` traversal (the path must still resolve under
  // catalogDir or overlayDir).
  const resolved = path.resolve(filePath);
  if (!resolved.startsWith(catalogDir) && !resolved.startsWith(overlayDir)) {
    res.statusCode = 403; res.end("forbidden"); return;
  }
  try {
    const stat = await fsp.stat(resolved);
    if (!stat.isFile()) { res.statusCode = 404; res.end("not a file"); return; }
    res.statusCode = 200;
    res.setHeader("Content-Type",   MIMES[path.extname(resolved).toLowerCase()] || "application/octet-stream");
    res.setHeader("Content-Length", stat.size);
    res.setHeader("Cache-Control",  "no-store");
    createReadStream(resolved).pipe(res);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") {
      res.statusCode = 404; res.end("not found");
    } else throw err;
  }
}

let _indexCache: { mtime: number; payload: string } | null = null;

async function sendOverlayIndex(res: import("node:http").ServerResponse): Promise<void> {
  // Skip the readdir hit on hot-reload by caching against the overlay
  // dir's mtime.  Once the underlying directory changes (e.g. a fresh
  // unpack) we regenerate.
  const stat = await fsp.stat(overlayDir);
  const mtime = stat.mtimeMs;
  if (_indexCache && _indexCache.mtime === mtime) {
    res.statusCode = 200;
    res.setHeader("Content-Type", "application/json");
    res.end(_indexCache.payload);
    return;
  }
  const entries = await fsp.readdir(overlayDir, { withFileTypes: true });
  const files   = entries.filter(e => e.isFile()).map(e => e.name).sort();
  const payload = JSON.stringify(files);
  _indexCache = { mtime, payload };
  try {
    fs.writeFileSync(indexCachePath, payload);
  } catch { /* best effort */ }
  res.statusCode = 200;
  res.setHeader("Content-Type",  "application/json");
  res.setHeader("Cache-Control", "no-store");
  res.end(payload);
}

