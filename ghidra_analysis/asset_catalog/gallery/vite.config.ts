/** Bridges a browser WebSocket at `/__lsp` to a `luau-lsp lsp` child
 *  process over stdio (the jsonrpc-ws-proxy pattern). The server is
 *  spawned in the paks dir so its `.luaurc` alias map (`@bulanci`, the
 *  lib aliases) resolves `require`s exactly as the engine does. The
 *  Scripts panel connects here for completion/hover/diagnostics; if the
 *  `luau-lsp` binary isn't installed the editor still works, just
 *  without language intelligence (`/__lsp/info` reports availability). */
function bulanciLuauLsp(): Plugin {
  // Probe once: is the binary on PATH? (cheap `--version`).
  let available = false;
  try {
    const r = spawnSync("luau-lsp", ["--version"], { encoding: "utf-8" });
    available = r.status === 0;
  } catch { available = false; }
  if (!available) {
    console.log("[luau-lsp] binary not found on PATH — Scripts panel runs without LSP (install JohnnyMorganz/luau-lsp to enable)");
  }

  const wss = new WebSocketServer({ noServer: true });

  return {
    name: "bulanci-luau-lsp",
    configureServer(server) {
      server.httpServer?.on("upgrade", (req, socket, head) => {
        let pathname = "";
        try { pathname = new URL(req.url ?? "", "http://localhost").pathname; } catch { /* ignore */ }
        if (pathname !== "/__lsp") return;
        if (!available) { socket.destroy(); return; }
        wss.handleUpgrade(req, socket, head, (ws) => {
          // Bridge the socket to a fresh luau-lsp process. One server per
          // connection keeps document state isolated and lets a crashed
          // server be recovered by reconnecting.
          const wsSocket = toSocket(ws as unknown as WebSocket);
          const connection = createWebSocketConnection(wsSocket);
          let serverProc: ReturnType<typeof createServerProcess> | undefined;
          try {
            serverProc = createServerProcess("luau", "luau-lsp", ["lsp"], { cwd: paksDir });
          } catch (e) {
            console.error("[luau-lsp] spawn failed:", e);
          }
          if (serverProc) {
            forward(connection, serverProc, (message) => message);
            console.log("[luau-lsp] client connected -> spawned luau-lsp lsp");
          } else {
            wsSocket.dispose();
            try { ws.close(); } catch { /* ignore */ }
          }
        });
      });

      server.middlewares.use((req, res, next) => {
        if ((req.url ?? "").split("?")[0] !== "/__lsp/info") return next();
        res.statusCode = 200;
        res.setHeader("Content-Type", "application/json");
        res.setHeader("Cache-Control", "no-store");
        // `root` lets the client mint `file://` URIs the server resolves
        // .luaurc against; `alias` documents the require root.
        res.end(JSON.stringify({ available, root: paksDir, alias: { bulanci: "@bulanci" } }));
      });
    },
  };
}

