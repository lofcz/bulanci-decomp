interface SceneRefWire {
  pak: string;
  name: string;
  kind: "declarative" | "module";
  doc?: string;
  scripts: string[];
  file?: string;
  writable: boolean;
}

/** Read the load-order profile and each folder pak's `pak.json`, flattening
 *  the `scenes` tables into a single list tagged by owning pak. */
function enumerateScenes(): SceneRefWire[] {
  let profile: { paks?: { id?: string; kind?: string; path?: string }[] } = {};
  try {
    profile = JSON.parse(fs.readFileSync(path.join(paksDir, "profile.json"), "utf-8"));
  } catch {
    return [];
  }
  const out: SceneRefWire[] = [];
  for (const entry of profile.paks ?? []) {
    if (!entry?.id || entry.kind === "master") continue; // master ships embedded
    const folder = entry.path ?? entry.id;
    const dir = path.join(paksDir, folder);
    let manifest: { scenes?: Record<string, { file?: string; doc?: string; scripts?: string[] }> } = {};
    try {
      manifest = JSON.parse(fs.readFileSync(path.join(dir, "pak.json"), "utf-8"));
    } catch {
      continue;
    }
    // A folder mod pak is always writable through the broker.
    const writable = entry.kind === "mod";
    for (const [name, scene] of Object.entries(manifest.scenes ?? {})) {
      out.push({
        pak: entry.id,
        name,
        kind: scene.doc ? "declarative" : "module",
        doc: scene.doc,
        scripts: scene.scripts ?? [],
        file: scene.file,
        writable,
      });
    }
  }
  return out;
}

function sendScenes(res: import("node:http").ServerResponse): void {
  const payload = JSON.stringify({ scenes: enumerateScenes() });
  res.statusCode = 200;
  res.setHeader("Content-Type", "application/json");
  res.setHeader("Cache-Control", "no-store");
  res.end(payload);
}

/** Map a pak id to its on-disk folder via the profile (defaults to the id). */
function pakFolder(pak: string): string {
  try {
    const profile = JSON.parse(fs.readFileSync(path.join(paksDir, "profile.json"), "utf-8")) as {
      paks?: { id?: string; path?: string }[];
    };
    const entry = (profile.paks ?? []).find(p => p.id === pak);
    if (entry?.path) return entry.path;
  } catch { /* default to id */ }
  return pak;
}

/** Recursively list every `.luau` under a pak folder, as pak-relative
 *  POSIX paths (the Scripts panel's file browser). */
function sendPakScripts(res: import("node:http").ServerResponse, pak: string): void {
  if (!/^[A-Za-z0-9_-]+$/.test(pak)) {
    res.statusCode = 400; res.end("bad pak id"); return;
  }
  const root = path.resolve(paksDir, pakFolder(pak));
  const out: string[] = [];
  const walk = (dir: string): void => {
    let ents: fs.Dirent[] = [];
    try { ents = fs.readdirSync(dir, { withFileTypes: true }); } catch { return; }
    for (const ent of ents) {
      const abs = path.join(dir, ent.name);
      if (ent.isDirectory()) { walk(abs); continue; }
      if (ent.name.endsWith(".luau")) {
        out.push(path.relative(root, abs).replace(/\\/g, "/"));
      }
    }
  };
  if (root === paksDir || root.startsWith(paksDir + path.sep)) walk(root);
  out.sort();
  res.statusCode = 200;
  res.setHeader("Content-Type", "application/json");
  res.setHeader("Cache-Control", "no-store");
  res.end(JSON.stringify({ scripts: out }));
}

/** Resolve `<pakId>/<relpath>` to an absolute path under `paksDir`,
 *  refusing `..` escapes and unknown paks. Returns null on any violation. */
function resolvePakFile(rel: string): { abs: string; pak: string; relPath: string } | null {
  const slash = rel.indexOf("/");
  if (slash <= 0) return null;
  const pak = rel.slice(0, slash);
  const relPath = rel.slice(slash + 1);
  if (!relPath || !/^[A-Za-z0-9_-]+$/.test(pak)) return null;
  // Map pak id -> folder via the profile (defaults to the id).
  let folder = pak;
  try {
    const profile = JSON.parse(fs.readFileSync(path.join(paksDir, "profile.json"), "utf-8")) as {
      paks?: { id?: string; path?: string }[];
    };
    const entry = (profile.paks ?? []).find(p => p.id === pak);
    if (entry?.path) folder = entry.path;
  } catch { /* default to id */ }
  const pakDir = path.resolve(paksDir, folder);
  const abs = path.resolve(pakDir, relPath);
  if (abs !== pakDir && !abs.startsWith(pakDir + path.sep)) return null;
  return { abs, pak, relPath };
}

async function readPakFile(res: import("node:http").ServerResponse, rel: string): Promise<void> {
  const r = resolvePakFile(rel);
  if (!r) { res.statusCode = 400; res.end("bad pak path"); return; }
  try {
    const stat = await fsp.stat(r.abs);
    if (!stat.isFile()) { res.statusCode = 404; res.end("not a file"); return; }
    res.statusCode = 200;
    res.setHeader("Content-Type", MIMES[path.extname(r.abs).toLowerCase()] || "text/plain; charset=utf-8");
    res.setHeader("Content-Length", stat.size);
    res.setHeader("Cache-Control", "no-store");
    createReadStream(r.abs).pipe(res);
  } catch (err) {
    if ((err as NodeJS.ErrnoException).code === "ENOENT") { res.statusCode = 404; res.end("not found"); }
    else throw err;
  }
}

async function writePakFile(
  req: import("node:http").IncomingMessage,
  res: import("node:http").ServerResponse,
  rel: string,
): Promise<void> {
  const r = resolvePakFile(rel);
  if (!r) { res.statusCode = 400; res.end("bad pak path"); return; }
  const chunks: Buffer[] = [];
  let total = 0;
  const MAX = 8 * 1024 * 1024;
  for await (const chunk of req) {
    chunks.push(chunk as Buffer);
    total += (chunk as Buffer).length;
    if (total > MAX) { res.statusCode = 413; res.end("file too large"); return; }
  }
  const body = Buffer.concat(chunks).toString("utf-8");
  // A `.scene.json` doc must parse as JSON before we overwrite it; scripts
  // are written as-is (the editor's Luau LSP validates those).
  if (r.relPath.endsWith(".json")) {
    try { JSON.parse(body); }
    catch (err) { res.statusCode = 400; res.end(`invalid JSON: ${err}`); return; }
  }
  await fsp.mkdir(path.dirname(r.abs), { recursive: true });
  const tmp = `${r.abs}.${process.pid}.tmp`;
  await fsp.writeFile(tmp, body, "utf-8");
  await fsp.rename(tmp, r.abs);
  res.statusCode = 200;
  res.setHeader("Content-Type", "application/json");
  res.end(JSON.stringify({ ok: true, pak: r.pak, path: r.relPath, bytes: body.length }));
  console.log(`[bulanci-data-source] pak file written ${r.pak}/${r.relPath} (${body.length} bytes)`);
}

