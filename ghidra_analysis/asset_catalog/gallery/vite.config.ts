interface PakEntry { id: string; kind: string; path?: string; file?: string; enabled: boolean }

/** Read the load-order profile + per-pak manifests, write live pushes
 *  through to the active mod pak folder, and seed the broker snapshot
 *  from already-persisted overrides. The native client watches the same
 *  folders, so one push persists *and* hot-reloads both targets. */
class PakStore {
  activeId: string;
  private queue: Promise<void> = Promise.resolve();

  constructor() {
    const paks = this.listPaks();
    const mods = paks.filter(p => p.kind === "mod" && p.enabled);
    // Default write-target: the highest-priority mod (last in load order),
    // falling back to the conventional dev pak.
    this.activeId = mods.length ? mods[mods.length - 1].id : "dev_overrides";
  }

  listPaks(): PakEntry[] {
    try {
      const raw = fs.readFileSync(path.join(paksDir, "profile.json"), "utf-8");
      const prof = JSON.parse(raw) as { paks?: Partial<PakEntry>[] };
      return (prof.paks ?? []).map(p => ({
        id: p.id ?? "",
        kind: p.kind ?? "mod",
        path: p.path,
        file: p.file,
        enabled: p.enabled ?? true,
      }));
    } catch {
      return [];
    }
  }

  setActive(id: string): boolean {
    const ok = this.listPaks().some(p => p.id === id && p.kind === "mod");
    if (ok) this.activeId = id;
    return ok;
  }

  private dirFor(id: string): string | null {
    const e = this.listPaks().find(p => p.id === id && p.kind === "mod" && p.enabled && !p.file);
    if (!e) return null;
    return path.join(paksDir, e.path ?? e.id);
  }

  /** Walk every enabled folder mod pak (low -> high) and load its content
   *  files into `overlays`, recording which hashes are disk-backed. */
  seed(overlays: Map<string, Buffer>, persisted: Set<string>): void {
    for (const p of this.listPaks()) {
      if (p.kind !== "mod" || !p.enabled || p.file) continue;
      const dir = path.join(paksDir, p.path ?? p.id);
      let manifest: any = {};
      try { manifest = JSON.parse(fs.readFileSync(path.join(dir, "pak.json"), "utf-8")); } catch { /* none */ }
      const fileToHash = new Map<string, string>();
      for (const [hashHex, a] of Object.entries((manifest.assets ?? {}) as Record<string, { file?: string }>)) {
        if (a.file) fileToHash.set(a.file.replace(/\\/g, "/"), hashHex);
      }
      const walk = (d: string): void => {
        let ents: fs.Dirent[] = [];
        try { ents = fs.readdirSync(d, { withFileTypes: true }); } catch { return; }
        for (const ent of ents) {
          const abs = path.join(d, ent.name);
          if (ent.isDirectory()) { walk(abs); continue; }
          const rel = path.relative(dir, abs).replace(/\\/g, "/");
          if (rel === "pak.json" || rel.endsWith(".schema.json")) continue;
          const stem = ent.name.replace(/\.[^.]*$/, "");
          let hash = fileToHash.get(rel);
          if (!hash && /^[0-9a-f]{16}$/i.test(stem)) hash = stem.toLowerCase();
          if (!hash) continue; // path-keyed (scenes/levels) — engine reads those itself
          try {
            overlays.set(hash, fs.readFileSync(abs));
            persisted.add(hash);
          } catch { /* skip */ }
        }
      };
      walk(dir);
    }
  }

  private serialize<T>(fn: () => Promise<T>): Promise<T> {
    const run = this.queue.then(fn, fn);
    this.queue = run.then(() => undefined, () => undefined);
    return run;
  }

  /** Persist a pushed override: write `<hash><ext>` into the active pak
   *  and record/update its `pak.json` entry. Returns false if there is no
   *  writable active pak folder. */
  async write(hashHex: string, buf: Buffer, meta: { ext?: string; slug?: string; folder?: string; className?: string }): Promise<boolean> {
    const dir = this.dirFor(this.activeId);
    if (!dir) return false;
    let ext = (meta.ext ?? "").trim().toLowerCase();
    if (ext && !ext.startsWith(".")) ext = "." + ext;
    if (!ext) ext = ".bin";
    const file = `${hashHex}${ext}`;
    return this.serialize(async () => {
      await fsp.mkdir(dir, { recursive: true });
      // Drop any stale same-hash file with a different extension.
      try {
        for (const n of await fsp.readdir(dir)) {
          if (n.startsWith(hashHex + ".") && n !== file) await fsp.rm(path.join(dir, n));
        }
      } catch { /* ignore */ }
      const tmp = path.join(dir, `${file}.${process.pid}.tmp`);
      await fsp.writeFile(tmp, buf);
      await fsp.rename(tmp, path.join(dir, file));
      await this.patchManifest(dir, (m) => {
        m.assets ??= {};
        m.assets[hashHex] = {
          ...(meta.folder ? { folder: meta.folder } : {}),
          ...(meta.slug ? { slug: meta.slug } : {}),
          ...(meta.className ? { class: meta.className } : {}),
          file,
          overrides: true,
        };
      });
      console.log(`[mod-broker] persisted ${hashHex} -> ${this.activeId}/${file} (${buf.length} bytes)`);
      return true;
    });
  }

  async remove(hashHex: string): Promise<void> {
    const dir = this.dirFor(this.activeId);
    if (!dir) return;
    await this.serialize(async () => {
      try {
        for (const n of await fsp.readdir(dir)) {
          if (n.startsWith(hashHex + ".") || n === hashHex) await fsp.rm(path.join(dir, n));
        }
      } catch { /* ignore */ }
      await this.patchManifest(dir, (m) => { if (m.assets) delete m.assets[hashHex]; });
    });
  }

  private async patchManifest(dir: string, mutate: (m: any) => void): Promise<void> {
    const p = path.join(dir, "pak.json");
    let m: any = {};
    try { m = JSON.parse(await fsp.readFile(p, "utf-8")); } catch { m = {}; }
    if (!m.schema) m.schema = 1;
    if (!m.id) m.id = path.basename(dir);
    if (!m.kind) m.kind = "mod";
    mutate(m);
    const tmp = `${p}.${process.pid}.tmp`;
    await fsp.writeFile(tmp, JSON.stringify(m, null, 2) + "\n", "utf-8");
    await fsp.rename(tmp, p);
  }
}

